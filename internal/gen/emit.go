package main

import (
	"fmt"
	"go/format"
	"sort"
	"strings"
)

// EmitTypes renders every non-excluded $defs declaration in m as Go source
// for protocol/types_gen.go. Output is deterministic: Model.Types is already
// sorted by name, and every nested emission (fields, variants) walks slices
// in the order BuildModel established, never a Go map.
func EmitTypes(m *Model) ([]byte, error) {
	byName := make(map[string]TypeDecl, len(m.Types))
	for _, d := range m.Types {
		byName[d.Name] = d
	}

	var b strings.Builder
	b.WriteString("// Code generated by internal/gen from the pinned ACP schema. DO NOT EDIT.\n")
	b.WriteString("// Regenerate with: go generate ./protocol/...\n\n")
	b.WriteString("package protocol\n\n")
	b.WriteString("import (\n\t\"encoding/json\"\n\t\"fmt\"\n)\n\n")

	for _, d := range m.Types {
		if err := emitDecl(&b, d, byName); err != nil {
			return nil, fmt.Errorf("emit %s: %w", d.Name, err)
		}
	}

	return format.Source([]byte(b.String()))
}

func emitDecl(b *strings.Builder, d TypeDecl, byName map[string]TypeDecl) error {
	switch d.Kind {
	case KindScalar:
		emitDoc(b, d.Name, d.Doc)
		fmt.Fprintf(b, "type %s %s\n\n", d.Name, d.Underlying)
		return nil
	case KindEnum:
		return emitEnum(b, d)
	case KindObject:
		return emitObject(b, d, byName)
	default:
		return fmt.Errorf("unknown decl kind %v", d.Kind)
	}
}

func emitDoc(b *strings.Builder, name, doc string) {
	lines := strings.Split(strings.TrimRight(doc, "\n"), "\n")
	if doc == "" {
		fmt.Fprintf(b, "// %s is generated from the pinned ACP schema.\n", name)
		return
	}
	first := true
	for _, line := range lines {
		if first {
			fmt.Fprintf(b, "// %s %s\n", name, line)
			first = false
			continue
		}
		if line == "" {
			b.WriteString("//\n")
			continue
		}
		fmt.Fprintf(b, "// %s\n", line)
	}
}

func emitEnum(b *strings.Builder, d TypeDecl) error {
	emitDoc(b, d.Name, d.Doc)
	fmt.Fprintf(b, "type %s %s\n\n", d.Name, d.Underlying)

	if len(d.Members) > 0 {
		b.WriteString("const (\n")
		for _, mem := range d.Members {
			if mem.Doc != "" {
				for _, line := range strings.Split(strings.TrimRight(mem.Doc, "\n"), "\n") {
					fmt.Fprintf(b, "\t// %s\n", line)
				}
			}
			fmt.Fprintf(b, "\t%s %s = %s\n", mem.Name, d.Name, mem.Value)
		}
		b.WriteString(")\n\n")
	}

	if d.Strict {
		lit := "string"
		if d.Underlying != "string" {
			lit = d.Underlying
		}
		fmt.Fprintf(b, "// UnmarshalJSON rejects any %s value that is not one of the named\n", d.Name)
		fmt.Fprintf(b, "// %s constants: this enum is closed in the pinned schema.\n", d.Name)
		fmt.Fprintf(b, "func (v *%s) UnmarshalJSON(data []byte) error {\n", d.Name)
		fmt.Fprintf(b, "\tvar raw %s\n", lit)
		b.WriteString("\tif err := json.Unmarshal(data, &raw); err != nil {\n")
		fmt.Fprintf(b, "\t\treturn fmt.Errorf(\"%s: %%w\", err)\n", d.Name)
		b.WriteString("\t}\n")
		fmt.Fprintf(b, "\tswitch %s(raw) {\n", d.Name)
		b.WriteString("\tcase ")
		names := make([]string, len(d.Members))
		for i, mem := range d.Members {
			names[i] = mem.Name
		}
		b.WriteString(strings.Join(names, ", "))
		b.WriteString(":\n")
		fmt.Fprintf(b, "\t\t*v = %s(raw)\n", d.Name)
		b.WriteString("\t\treturn nil\n")
		b.WriteString("\tdefault:\n")
		fmt.Fprintf(b, "\t\treturn fmt.Errorf(\"%s: unrecognized value %%v\", raw)\n", d.Name)
		b.WriteString("\t}\n")
		b.WriteString("}\n\n")
	}
	return nil
}

func emitObject(b *strings.Builder, d TypeDecl, byName map[string]TypeDecl) error {
	if d.UnionMode == UnionAlias {
		emitDoc(b, d.Name, d.Doc)
		fmt.Fprintf(b, "type %s = %s\n\n", d.Name, d.AliasOf)
		return nil
	}

	emitDoc(b, d.Name, d.Doc)
	fmt.Fprintf(b, "type %s struct {\n", d.Name)
	for _, f := range d.Fields {
		emitFieldDoc(b, f)
		tag := jsonTag(f)
		fmt.Fprintf(b, "\t%s %s `json:%q`\n", f.GoName, f.GoType, tag)
	}
	for _, v := range d.Variants {
		if v.Doc != "" {
			for _, line := range strings.Split(strings.TrimRight(v.Doc, "\n"), "\n") {
				fmt.Fprintf(b, "\t// %s\n", line)
			}
		}
		fmt.Fprintf(b, "\t%s %s `json:\"-\"`\n", v.GoName, variantFieldType(v))
	}
	b.WriteString("}\n\n")

	if d.HasDefaults() {
		emitDefaultConstructor(b, d)
	}

	switch d.UnionMode {
	case UnionDiscriminated:
		return emitDiscriminatedCodec(b, d)
	case UnionStructural:
		return emitStructuralCodec(b, d, byName)
	default:
		return nil
	}
}

func emitFieldDoc(b *strings.Builder, f Field) {
	if f.Doc == "" {
		return
	}
	for _, line := range strings.Split(strings.TrimRight(f.Doc, "\n"), "\n") {
		fmt.Fprintf(b, "\t// %s\n", line)
	}
}

// variantFieldType renders a union variant's Go field type. Slice-typed
// variants (a branch that is itself an array, e.g.
// SessionConfigSelectOptions) are already nil-able and stay plain slices,
// exactly like ordinary optional array Fields; every other variant is a
// pointer to its payload type so "unset" is representable.
func variantFieldType(v Variant) string {
	if strings.HasPrefix(v.Type, "[]") {
		return v.Type
	}
	return "*" + v.Type
}

func jsonTag(f Field) string {
	if !f.Required || f.IsMeta {
		return f.JSONKey + ",omitempty"
	}
	return f.JSONKey
}

func emitDefaultConstructor(b *strings.Builder, d TypeDecl) {
	fmt.Fprintf(b, "// Default%s returns %s with every schema-declared default applied.\n", d.Name, d.Name)
	fmt.Fprintf(b, "func Default%s() %s {\n", d.Name, d.Name)
	fmt.Fprintf(b, "\treturn %s{\n", d.Name)
	for _, f := range d.Fields {
		if f.DefaultLiteral == "" {
			continue
		}
		if strings.HasPrefix(f.GoType, "*") && strings.HasSuffix(f.DefaultLiteral, "()") {
			inner := strings.TrimPrefix(f.GoType, "*")
			fmt.Fprintf(b, "\t\t%s: func() %s { v := %s; return &v }(),\n", f.GoName, f.GoType, f.DefaultLiteral)
			_ = inner
			continue
		}
		fmt.Fprintf(b, "\t\t%s: %s,\n", f.GoName, f.DefaultLiteral)
	}
	b.WriteString("\t}\n}\n\n")
}

// emitDiscriminatedCodec emits MarshalJSON/UnmarshalJSON for a struct whose
// variants are told apart by a shared tag field (d.DiscKey) carrying a
// distinct string const. MarshalJSON rejects zero or multiple variants set;
// UnmarshalJSON rejects an unrecognized (or, absent a fallback variant,
// missing) tag value.
func emitDiscriminatedCodec(b *strings.Builder, d TypeDecl) error {
	name := d.Name

	fmt.Fprintf(b, "// MarshalJSON flattens whichever %s variant is set, plus the %q\n", name, d.DiscKey)
	b.WriteString("// discriminator, into one JSON object. It fails if zero or more than one\n")
	b.WriteString("// variant is set.\n")
	fmt.Fprintf(b, "func (v %s) MarshalJSON() ([]byte, error) {\n", name)
	b.WriteString("\tset := 0\n")
	b.WriteString("\tmerged := map[string]json.RawMessage{}\n")
	for _, v := range d.Variants {
		fmt.Fprintf(b, "\tif v.%s != nil {\n", v.GoName)
		b.WriteString("\t\tset++\n")
		fmt.Fprintf(b, "\t\traw, err := json.Marshal(v.%s)\n", v.GoName)
		b.WriteString("\t\tif err != nil {\n\t\t\treturn nil, err\n\t\t}\n")
		b.WriteString("\t\tif err := json.Unmarshal(raw, &merged); err != nil {\n\t\t\treturn nil, err\n\t\t}\n")
		if !v.IsFallback {
			fmt.Fprintf(b, "\t\ttagBytes, err := json.Marshal(%q)\n", v.Tag)
			b.WriteString("\t\tif err != nil {\n\t\t\treturn nil, err\n\t\t}\n")
			fmt.Fprintf(b, "\t\tmerged[%q] = tagBytes\n", d.DiscKey)
		}
		b.WriteString("\t}\n")
	}
	b.WriteString("\tif set == 0 {\n")
	fmt.Fprintf(b, "\t\treturn nil, fmt.Errorf(\"%s: no variant set\")\n", name)
	b.WriteString("\t}\n")
	b.WriteString("\tif set > 1 {\n")
	fmt.Fprintf(b, "\t\treturn nil, fmt.Errorf(\"%s: more than one variant set\")\n", name)
	b.WriteString("\t}\n")
	for _, f := range d.Fields {
		fmt.Fprintf(b, "\t{\n\t\tfbytes, err := json.Marshal(v.%s)\n\t\tif err != nil {\n\t\t\treturn nil, err\n\t\t}\n\t\tmerged[%q] = fbytes\n\t}\n", f.GoName, f.JSONKey)
	}
	b.WriteString("\treturn json.Marshal(merged)\n}\n\n")

	fallback := ""
	for _, v := range d.Variants {
		if v.IsFallback {
			fallback = v.GoName
		}
	}

	fmt.Fprintf(b, "// UnmarshalJSON dispatches on the %q discriminator.", d.DiscKey)
	if fallback != "" {
		fmt.Fprintf(b, " A missing or\n// unrecognized value falls back to %s, matching the pinned schema.\n", fallback)
	} else {
		b.WriteString(" A missing or\n// unrecognized value is rejected.\n")
	}
	fmt.Fprintf(b, "func (v *%s) UnmarshalJSON(data []byte) error {\n", name)
	b.WriteString("\tvar tag struct {\n")
	fmt.Fprintf(b, "\t\tValue *string `json:%q`\n", d.DiscKey)
	b.WriteString("\t}\n")
	b.WriteString("\tif err := json.Unmarshal(data, &tag); err != nil {\n")
	fmt.Fprintf(b, "\t\treturn fmt.Errorf(\"%s: %%w\", err)\n", name)
	b.WriteString("\t}\n")
	fmt.Fprintf(b, "\t*v = %s{}\n", name)
	b.WriteString("\tswitch {\n")
	for _, v := range d.Variants {
		if v.IsFallback {
			continue
		}
		fmt.Fprintf(b, "\tcase tag.Value != nil && *tag.Value == %q:\n", v.Tag)
		fmt.Fprintf(b, "\t\tvar payload %s\n", v.Type)
		b.WriteString("\t\tif err := json.Unmarshal(data, &payload); err != nil {\n")
		fmt.Fprintf(b, "\t\t\treturn fmt.Errorf(\"%s: %s: %%w\", err)\n", name, v.Tag)
		b.WriteString("\t\t}\n")
		fmt.Fprintf(b, "\t\tv.%s = &payload\n", v.GoName)
	}
	if fallback != "" {
		var fv Variant
		for _, v := range d.Variants {
			if v.IsFallback {
				fv = v
			}
		}
		b.WriteString("\tdefault:\n")
		fmt.Fprintf(b, "\t\tvar payload %s\n", fv.Type)
		b.WriteString("\t\tif err := json.Unmarshal(data, &payload); err != nil {\n")
		fmt.Fprintf(b, "\t\t\treturn fmt.Errorf(\"%s: %%w\", err)\n", name)
		b.WriteString("\t\t}\n")
		fmt.Fprintf(b, "\t\tv.%s = &payload\n", fv.GoName)
	} else {
		b.WriteString("\tcase tag.Value == nil:\n")
		fmt.Fprintf(b, "\t\treturn fmt.Errorf(\"%s: missing discriminator field %s\")\n", name, d.DiscKey)
		b.WriteString("\tdefault:\n")
		fmt.Fprintf(b, "\t\treturn fmt.Errorf(\"%s: unrecognized %s %%q\", *tag.Value)\n", name, d.DiscKey)
	}
	b.WriteString("\t}\n")
	if len(d.Fields) > 0 {
		b.WriteString("\tvar base struct {\n")
		for _, f := range d.Fields {
			fmt.Fprintf(b, "\t\t%s %s `json:%q`\n", f.GoName, f.GoType, f.JSONKey)
		}
		b.WriteString("\t}\n")
		b.WriteString("\tif err := json.Unmarshal(data, &base); err != nil {\n")
		fmt.Fprintf(b, "\t\treturn fmt.Errorf(\"%s: %%w\", err)\n", name)
		b.WriteString("\t}\n")
		for _, f := range d.Fields {
			fmt.Fprintf(b, "\tv.%s = base.%s\n", f.GoName, f.GoName)
		}
	}
	b.WriteString("\treturn nil\n}\n\n")
	return nil
}

// emitStructuralCodec emits MarshalJSON/UnmarshalJSON for a struct whose
// variants carry no discriminator tag at all; UnmarshalJSON tells them apart
// by which variant's required JSON keys are all present on the wire object.
func emitStructuralCodec(b *strings.Builder, d TypeDecl, byName map[string]TypeDecl) error {
	name := d.Name

	fmt.Fprintf(b, "// MarshalJSON marshals whichever %s variant is set. It fails if zero or\n", name)
	b.WriteString("// more than one variant is set.\n")
	fmt.Fprintf(b, "func (v %s) MarshalJSON() ([]byte, error) {\n", name)
	b.WriteString("\tset := 0\n")
	b.WriteString("\tvar out []byte\n")
	for _, v := range d.Variants {
		fmt.Fprintf(b, "\tif v.%s != nil {\n", v.GoName)
		b.WriteString("\t\tset++\n")
		b.WriteString("\t\tvar err error\n")
		fmt.Fprintf(b, "\t\tout, err = json.Marshal(v.%s)\n", v.GoName)
		b.WriteString("\t\tif err != nil {\n\t\t\treturn nil, err\n\t\t}\n")
		b.WriteString("\t}\n")
	}
	b.WriteString("\tif set == 0 {\n")
	fmt.Fprintf(b, "\t\treturn nil, fmt.Errorf(\"%s: no variant set\")\n", name)
	b.WriteString("\t}\n")
	b.WriteString("\tif set > 1 {\n")
	fmt.Fprintf(b, "\t\treturn nil, fmt.Errorf(\"%s: more than one variant set\")\n", name)
	b.WriteString("\t}\n")
	b.WriteString("\treturn out, nil\n}\n\n")

	arrayMode, err := structuralUnionIsArrayMode(d)
	if err != nil {
		return err
	}

	fmt.Fprintf(b, "// UnmarshalJSON tells %s's variants apart by which one's required fields\n", name)
	if arrayMode {
		b.WriteString("// are present on the first array element (this union has no discriminator\n")
		b.WriteString("// tag, and each variant is itself an array of a different element type).\n")
	} else {
		b.WriteString("// are present on the wire object (this union has no discriminator tag).\n")
	}
	fmt.Fprintf(b, "func (v *%s) UnmarshalJSON(data []byte) error {\n", name)
	if arrayMode {
		b.WriteString("\tvar arr []json.RawMessage\n")
		b.WriteString("\tif err := json.Unmarshal(data, &arr); err != nil {\n")
		fmt.Fprintf(b, "\t\treturn fmt.Errorf(\"%s: %%w\", err)\n", name)
		b.WriteString("\t}\n")
		fmt.Fprintf(b, "\t*v = %s{}\n", name)
		b.WriteString("\tif len(arr) == 0 {\n")
		fmt.Fprintf(b, "\t\treturn fmt.Errorf(\"%s: empty array is ambiguous between variants\")\n", name)
		b.WriteString("\t}\n")
		b.WriteString("\tvar probe map[string]json.RawMessage\n")
		b.WriteString("\tif err := json.Unmarshal(arr[0], &probe); err != nil {\n")
		fmt.Fprintf(b, "\t\treturn fmt.Errorf(\"%s: %%w\", err)\n", name)
		b.WriteString("\t}\n")
	} else {
		b.WriteString("\tvar probe map[string]json.RawMessage\n")
		b.WriteString("\tif err := json.Unmarshal(data, &probe); err != nil {\n")
		fmt.Fprintf(b, "\t\treturn fmt.Errorf(\"%s: %%w\", err)\n", name)
		b.WriteString("\t}\n")
		fmt.Fprintf(b, "\t*v = %s{}\n", name)
	}
	b.WriteString("\tmatches := 0\n")
	for _, variant := range d.Variants {
		elemName := strings.TrimPrefix(variant.Type, "[]")
		target, ok := byName[elemName]
		if !ok {
			return fmt.Errorf("structural variant %s: unknown payload type %s", variant.GoName, elemName)
		}
		var required []string
		for _, f := range target.Fields {
			if f.Required && !f.IsMeta {
				required = append(required, f.JSONKey)
			}
		}
		sort.Strings(required)
		if len(required) == 0 {
			return fmt.Errorf("structural variant %s (%s) has no required fields to distinguish it", variant.GoName, elemName)
		}
		conds := make([]string, len(required))
		for i, key := range required {
			conds[i] = fmt.Sprintf("probe[%q] != nil", key)
		}
		fmt.Fprintf(b, "\tif %s {\n", strings.Join(conds, " && "))
		fmt.Fprintf(b, "\t\tvar payload %s\n", variant.Type)
		b.WriteString("\t\tif err := json.Unmarshal(data, &payload); err != nil {\n")
		fmt.Fprintf(b, "\t\t\treturn fmt.Errorf(\"%s: %s: %%w\", err)\n", name, elemName)
		b.WriteString("\t\t}\n")
		if arrayMode {
			fmt.Fprintf(b, "\t\tv.%s = payload\n", variant.GoName)
		} else {
			fmt.Fprintf(b, "\t\tv.%s = &payload\n", variant.GoName)
		}
		b.WriteString("\t\tmatches++\n")
		b.WriteString("\t}\n")
	}
	b.WriteString("\tif matches == 0 {\n")
	fmt.Fprintf(b, "\t\treturn fmt.Errorf(\"%s: no variant's required fields are present\")\n", name)
	b.WriteString("\t}\n")
	b.WriteString("\tif matches > 1 {\n")
	fmt.Fprintf(b, "\t\treturn fmt.Errorf(\"%s: ambiguous, multiple variants match\")\n", name)
	b.WriteString("\t}\n")
	b.WriteString("\treturn nil\n}\n\n")
	return nil
}

// structuralUnionIsArrayMode reports whether every variant of a structural
// union is itself an array (true), or every variant is a plain object
// (false). The pinned schema never mixes the two within one union; a mix is
// rejected rather than silently mishandled.
func structuralUnionIsArrayMode(d TypeDecl) (bool, error) {
	arrayCount := 0
	for _, v := range d.Variants {
		if strings.HasPrefix(v.Type, "[]") {
			arrayCount++
		}
	}
	switch arrayCount {
	case 0:
		return false, nil
	case len(d.Variants):
		return true, nil
	default:
		return false, fmt.Errorf("structural union %s mixes array and object variants, which is unsupported", d.Name)
	}
}

// EmitMethods renders methods_gen.go: the agent/client/protocol method-name
// vocabulary from meta.json, as a named Method string type, individual
// per-method constants, and three sets (AgentMethods/ClientMethods/
// ProtocolMethods) usable for membership checks or iteration.
//
// The pinned schema's own ProtocolVersion type (a $defs entry: the uint16
// wire protocol version identifier used in InitializeRequest/
// InitializeResponse) collides with the literal constant name
// `ProtocolVersion` the implementation plan specifies for "the negotiated
// protocol version this module speaks". Per the plan's own rule ("pinned
// artifact wins; note the deviation"), the type keeps the schema's name and
// the version constant is named CurrentProtocolVersion instead.
func EmitMethods(m *Model) ([]byte, error) {
	var b strings.Builder
	b.WriteString("// Code generated by internal/gen from the pinned ACP schema. DO NOT EDIT.\n")
	b.WriteString("// Regenerate with: go generate ./protocol/...\n\n")
	b.WriteString("package protocol\n\n")

	b.WriteString("// Method is a JSON-RPC method name used by the Agent Client Protocol.\n")
	b.WriteString("type Method string\n\n")

	emitMethodConstBlock(&b, "agent-bound (client calls, agent implements)", m.Methods.Agent)
	emitMethodConstBlock(&b, "client-bound (agent calls, client implements)", m.Methods.Client)
	emitMethodConstBlock(&b, "protocol-level (either side may send; '$/' prefixed)", m.Methods.Protocol)

	emitMethodSet(&b, "AgentMethods", "agent-bound", m.Methods.Agent)
	emitMethodSet(&b, "ClientMethods", "client-bound", m.Methods.Client)
	emitMethodSet(&b, "ProtocolMethods", "protocol-level", m.Methods.Protocol)

	fmt.Fprintf(&b, "// CurrentProtocolVersion is the wire protocol version this module speaks,\n")
	fmt.Fprintf(&b, "// pinned from the schema's own \"version\" field (see protocol/schema/v1/REVISION).\n")
	fmt.Fprintf(&b, "const CurrentProtocolVersion ProtocolVersion = %d\n", m.Methods.Version)

	return format.Source([]byte(b.String()))
}

func emitMethodConstBlock(b *strings.Builder, label string, entries []MethodEntry) {
	if len(entries) == 0 {
		return
	}
	fmt.Fprintf(b, "// %s methods.\n", label)
	b.WriteString("const (\n")
	for _, e := range entries {
		fmt.Fprintf(b, "\t%s Method = %q\n", e.ConstName, e.Wire)
	}
	b.WriteString(")\n\n")
}

func emitMethodSet(b *strings.Builder, varName, label string, entries []MethodEntry) {
	fmt.Fprintf(b, "// %s is the set of %s method names.\n", varName, label)
	fmt.Fprintf(b, "var %s = map[Method]struct{}{\n", varName)
	for _, e := range entries {
		fmt.Fprintf(b, "\t%s: {},\n", e.ConstName)
	}
	b.WriteString("}\n\n")
}
